// Regenerates src/og-fonts.ts from the @fontsource/inter WOFF1 latin files so
// OpenGraph rendering carries its font bytes in the bundle (no runtime fetch).
// With --check, verifies the committed module is current instead of writing.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const packageRoot = new URL("..", import.meta.url);
const weights = ["400", "600", "700"];
const target = new URL("src/og-fonts.ts", packageRoot);

const banner = `// Generated by scripts/embed-og-fonts.mjs from @fontsource/inter — do not edit
// by hand. Inter latin subsets as WOFF1 (Satori's fontkit cannot read WOFF2),
// base64-embedded so OG image rendering makes zero outbound network requests.
// Regenerate with \`node scripts/embed-og-fonts.mjs\` after bumping
// @fontsource/inter; \`pnpm typecheck\` verifies the file is current.
`;

const generated =
	banner +
	"export const interLatinWoff = {\n" +
	weights.map((weight) => {
		const file = require.resolve(`@fontsource/inter/files/inter-latin-${weight}-normal.woff`);
		const bytes = readFileSync(file);
		if (bytes.subarray(0, 4).toString("latin1") !== "wOFF") {
			throw new Error(`${file} is not a WOFF1 font`);
		}
		return `\t"${weight}": "${bytes.toString("base64")}",`;
	}).join("\n") +
	"\n} as const;\n";

if (process.argv.includes("--check")) {
	const current = readFileSync(target, "utf8");
	if (current !== generated) {
		console.error(`${fileURLToPath(target)} is stale; run \`node scripts/embed-og-fonts.mjs\` to regenerate it`);
		process.exit(1);
	}
	console.log("og-fonts.ts matches @fontsource/inter");
} else {
	writeFileSync(target, generated);
	console.log(`Wrote ${fileURLToPath(target)} from @fontsource/inter WOFF1 files`);
}
